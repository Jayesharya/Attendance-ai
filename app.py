def _summary_cards(summary: dict[str, object]) -> None:
    columns = st.columns(4)
    columns[0].metric("Activity signal", f"{summary['mean_activity_signal']:.1f}/100")
    columns[1].metric("Present profiles", f"{summary['present_profiles']}/{summary['tracked_profiles']}")
    coverage = summary["roster_coverage"]
    columns[2].metric("Roster coverage", f"{coverage:.1f}%" if coverage is not None else "Not set")
    audio_mean = summary["mean_audio_dbfs"]
    columns[3].metric("Room audio", f"{audio_mean:.1f} dBFS" if audio_mean is not None else "Not provided")


def _show_result(result: dict[str, object], store: SessionStore) -> None:
    summary = result["summary"]
    metrics = result["metrics"]
    attendance = result["attendance"]
    _summary_cards(summary)
    st.caption(
        "The activity signal combines visible motion with speech-like audio when audio is supplied. "
        "It is a classroom-level heuristic, not a measure of learning or individual attention."
    )

    left, right = st.columns([1.45, 1], gap="large")
    with left:
        st.subheader("Session timeline")
        st.line_chart(metrics.set_index("elapsed_seconds")[["activity_signal", "motion_signal"]], height=300)
        st.dataframe(
            metrics[[
                "elapsed_seconds", "detected_faces", "present_profiles", "motion_signal",
                "audio_activity", "activity_signal",
            ]],
            width="stretch",
            hide_index=True,
        )
    with right:
        st.subheader("Teaching prompts")
        st.caption("Rule-based prompts are the default. Optional local AI uses only the summary numbers.")
        model_tag = st.text_input(
            "Optional local Ollama model tag",
            placeholder="Enter a model already installed on this computer",
            key="edusense_local_model_tag",
        )
        if model_tag.strip() and st.button("Generate local AI prompts", key="edusense_local_ai_button", width="stretch"):
            try:
                local_items = LocalTeachingAssistant(model_tag).suggest(summary)
                result["suggestions"] = [
                    {"title": item.title, "action": item.action, "reason": item.reason}
                    for item in local_items
                ]
                st.session_state["current_result"] = result
                st.success("Suggestions generated by your local model.")
            except (LocalModelError, ValueError) as error:
                st.warning(f"Local model unavailable; keeping rule-based prompts. {error}")
        for item in result["suggestions"]:
            with st.container(border=True):
                st.markdown(f"**{item['title']}**")
                st.write(item["action"])
                st.caption(item["reason"])
        st.subheader("Anonymous presence")
        st.dataframe(pd.DataFrame(attendance), width="stretch", hide_index=True)
        if result.get("preview_jpeg"):
            st.image(result["preview_jpeg"], caption="In-memory preview from the final sampled frame")

    csv_data = metrics.to_csv(index=False).encode("utf-8")
    pdf_data = make_pdf_report(
        str(result["started_at"]),
        str(result["source_label"]),
        summary,
        metrics,
    )
    export_col, pdf_col, save_col = st.columns([1, 1, 1])
    export_col.download_button(
        "Download session CSV",
        data=csv_data,
        file_name="edusense-session.csv",
        mime="text/csv",
        width="stretch",
    )
    pdf_col.download_button(
        "Download PDF summary",
        data=pdf_data,
        file_name="edusense-session.pdf",
        mime="application/pdf",
        width="stretch",
    )
    if result.get("saved_id"):
        save_col.success("Saved to local history")
    elif save_col.button("Save summary locally", width="stretch"):
        saved_id = store.save(
            str(result["source_label"]),
            summary,
            metrics,
            attendance,
            started_at=str(result["started_at"]),
        )
        result["saved_id"] = saved_id
        st.session_state["current_result"] = result
        st.success("Aggregate summary saved on this device.")


def _new_session(store: SessionStore) -> None:
    st.markdown(
        """
        <section class="hero">
          <div class="eyebrow">Local session</div>
          <h1>Start a classroom check-in</h1>
          <p>Choose a camera or a short video. Add a room-audio clip if you want signal context.</p>
        </section>
        """,
        unsafe_allow_html=True,
    )

    source_mode = st.radio("Video source", ["Local webcam", "Video file"], horizontal=True)
    video_upload = None
    camera_index = 0
    if source_mode == "Video file":
        video_upload = st.file_uploader(
            "Choose a video",
            type=["mp4", "mov", "avi", "mkv"],
            help="The file is analyzed locally and a temporary copy is removed after processing.",
        )
    else:
        camera_index = int(st.number_input("Camera index", min_value=0, max_value=8, value=0, step=1))
        st.caption("The webcam attached to the computer running this app is used.")

    audio_mode = st.radio(
        "Room audio (optional)",
        ["No audio", "Upload clip", "Record clip"],
        horizontal=True,
    )
    audio_upload = None
    audio_recording = None
    if audio_mode == "Upload clip":
        audio_upload = st.file_uploader(
            "Choose an audio clip",
            type=["wav", "flac", "ogg"],
            help="Audio is reduced to one-second activity measurements; it is not transcribed.",
        )
    elif audio_mode == "Record clip":
        audio_recording = st.audio_input(
            "Record room audio",
            sample_rate=16000,
            help="The recording is processed locally and is not included in saved session history.",
        )

    settings_left, settings_right = st.columns(2)
    with settings_left:
        max_seconds = st.slider("Maximum video duration (seconds)", 15, 300, 60, step=15)
    with settings_right:
        class_size_value = st.number_input(
            "Expected class size (optional)",
            min_value=0,
            max_value=300,
            value=0,
            step=1,
            help="Roster coverage is unavailable until a class size is entered. No names are collected.",
        )
    expected_size = int(class_size_value) or None

    if st.button("Analyze locally", type="primary", width="stretch"):
        if source_mode == "Video file" and video_upload is None:
            st.error("Choose a video file first.")
            return
        audio_bytes = None
        if audio_upload is not None:
            audio_bytes = audio_upload.getvalue()
        elif audio_recording is not None:
            audio_bytes = audio_recording.getvalue()

        temporary_path: str | None = None
        source: int | str = camera_index
        if source_mode == "Video file" and video_upload is not None:
            suffix = Path(video_upload.name).suffix or ".mp4"
            with NamedTemporaryFile(delete=False, suffix=suffix) as temporary_file:
                temporary_file.write(video_upload.getvalue())
                temporary_path = temporary_file.name
            source = temporary_path

        progress_bar = st.progress(0, text="Preparing local analysis")
        status = st.empty()

        def report_progress(fraction: float, message: str) -> None:
            progress_bar.progress(fraction, text=message)
            status.caption(message)

        try:
            with st.spinner("Analyzing sampled frames and optional audio windows locally"):
                result: SessionResult = analyze_session(
                    source,
                    max_seconds=float(max_seconds),
                    audio_bytes=audio_bytes,
                    expected_class_size=expected_size,
                    progress=report_progress,
                )
            st.session_state["current_result"] = {
                "started_at": result.started_at,
                "source_label": result.video.source_label,
                "duration_seconds": result.video.duration_seconds,
                "summary": result.summary,
                "metrics": result.metrics,
                "attendance": result.video.attendance,
                "suggestions": result.suggestions,
                "preview_jpeg": result.video.preview_jpeg,
                "saved_id": None,
            }
            st.success("Analysis complete. Review the signals alongside your classroom context.")
        except (RuntimeError, ValueError, OSError) as error:
            st.error(str(error))
        finally:
            if temporary_path:
                try:
                    os.unlink(temporary_path)
                except OSError:
                    st.warning("The temporary video file could not be removed automatically.")

    current = st.session_state.get("current_result")
    if current:
        st.divider()
        st.subheader("Latest session")
        _show_result(current, store)


def _history(store: SessionStore) -> None:
    st.markdown("## Session history")
    records = store.list()
    if not records:
        st.info("No saved sessions yet. Save a session summary from the analysis page to build local history.")
        return
    labels = {
        f"{row['started_at']} · {row['summary']['mean_activity_signal']:.1f}/100 · {row['source_label']} · {str(row['session_id'])[:8]}": row["session_id"]
        for row in records
    }
    selected = st.selectbox("Saved session", list(labels))
    record = store.load(labels[selected])
    if record is None:
        st.warning("That session is no longer available.")
        return
    _summary_cards(record["summary"])
    metrics = record["metrics"]
    st.line_chart(metrics.set_index("elapsed_seconds")[["activity_signal", "motion_signal"]], height=320)
    st.dataframe(metrics, width="stretch", hide_index=True)
    st.dataframe(pd.DataFrame(record["attendance"]), width="stretch", hide_index=True)
    st.download_button(
        "Download CSV",
        data=metrics.to_csv(index=False).encode("utf-8"),
        file_name="edusense-session.csv",
        mime="text/csv",
    )
    st.download_button(
        "Download PDF",
        data=make_pdf_report(
            str(record["started_at"]),
            str(record["source_label"]),
            record["summary"],
            metrics,
        ),
        file_name="edusense-session.pdf",
        mime="application/pdf",
    )
    st.divider()
    confirm_delete = st.checkbox("I understand this deletes saved summaries from this device.")
    if st.button("Clear saved history", disabled=not confirm_delete):
        removed = store.clear()
        st.success(f"Deleted {removed} saved session(s).")
        st.rerun()


def _overview(store: SessionStore) -> None:
    st.markdown(
        """
        <section class="hero">
          <div class="eyebrow">Teacher decision support</div>
          <h1>See classroom patterns with context</h1>
          <p>Anonymous presence and room-activity signals, processed on your device.</p>
        </section>
        """,
        unsafe_allow_html=True,
    )
    st.write(
        "EduSense AI helps teachers review broad session patterns. It does not recognize identities, "
        "transcribe speech, classify emotions, grade students, or assess teaching quality."
    )
    latest = st.session_state.get("current_result")
    if latest:
        st.subheader("Current session")
        _show_result(latest, store)
    else:
        recent = store.list()
        if recent:
            st.subheader("Latest saved session")
            record = store.load(str(recent[0]["session_id"]))
            if record:
                _summary_cards(record["summary"])
                st.caption(f"Saved {record['started_at']} · {record['source_label']}")
                st.line_chart(record["metrics"].set_index("elapsed_seconds")[["activity_signal", "motion_signal"]])
        else:
            st.info("Start a local session to see its summary here.")


def _privacy(store: SessionStore) -> None:
    st.markdown("## Privacy and limits")
    st.markdown(
        """
        - Video is sampled on the computer running EduSense AI. Frames are not written to saved history.
        - The final annotated frame may stay in the active Streamlit session until you clear it or close the page.
        - Audio becomes one-second level and signal-shape measurements. No transcript or speaker identity is produced.
        - Uploaded media may remain in the active app session until it is closed; a temporary video copy is removed after analysis.
        - Saved history contains aggregate measurements and anonymous session-only labels in a local SQLite file.
        - Face detection can miss people or create duplicate tracks. Check attendance against the class roster.
        - The activity signal is a transparent heuristic. It is not an objective measure of attention, learning, or performance.
        - Use only with appropriate classroom notice and consent, and keep human review in the loop.
        """
    )
    from edusense.storage import database_path
    st.caption(f"Local database path: {database_path()}")


def main() -> None:
    _apply_style()
    store = SessionStore()
    with st.sidebar:
        st.markdown(
            '<div class="brand"><span class="brand-mark">E</span><span class="brand-name">EduSense AI</span></div>',
            unsafe_allow_html=True,
        )
        page = st.radio("Workspace", ["Overview", "New session", "History", "Privacy"], label_visibility="collapsed")
        st.caption("Local-first · aggregate-only reports")

    if page == "Overview":
        _overview(store)
    elif page == "New session":
        _new_session(store)
    elif page == "History":
        _history(store)
    else:
        _privacy()


if __name__ == "__main__":
    main()
